#!/usr/bin/env node
/**
 * FAIR QuickRisk — run the whole application on this machine.
 *
 * Serves the compiled frontend and the PHP calculation endpoint from one origin using
 * PHP's built-in web server, so no Apache, MySQL, Node server or hosting account is
 * needed. One origin also means the endpoint's same-origin protection works exactly as
 * it does in production.
 *
 * Usage:
 *   node tools/serve-local.mjs                 # build if needed, then serve
 *   node tools/serve-local.mjs --build         # force a fresh frontend build first
 *   node tools/serve-local.mjs --port 8080     # serve on another port
 *   node tools/serve-local.mjs --no-validate   # skip the model deployment gate
 *
 * Environment:
 *   QUICKRISK_PHP   Path to the PHP CLI to use. Defaults to .tmp/php/php.exe (the
 *                   portable PHP used by this repository) and then to "php" on PATH.
 *
 * The generated override in .tmp/local-config.php allows plain HTTP and localhost
 * origins. It is written into .tmp/ (gitignored) and must never be used in production.
 */
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const distIndex = join(repoRoot, 'frontend', 'dist', 'index.html');
const tmpDir = join(repoRoot, '.tmp');
const localConfig = join(tmpDir, 'local-config.php');
const modelPath = join(repoRoot, 'fairquickmodel');

function readFlag(name) {
  return process.argv.includes(name);
}

function readOption(name, fallback) {
  const index = process.argv.indexOf(name);
  if (index === -1 || index + 1 >= process.argv.length) return fallback;
  return process.argv[index + 1];
}

function resolvePhp() {
  const candidates = [process.env.QUICKRISK_PHP, join(repoRoot, '.tmp', 'php', 'php.exe'), 'php'].filter(Boolean);
  for (const candidate of candidates) {
    if (candidate !== 'php' && !existsSync(candidate)) continue;
    const probe = spawnSync(candidate, ['-v'], { encoding: 'utf8' });
    if (probe.status === 0) return candidate;
  }
  return null;
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: repoRoot, stdio: 'inherit', ...options });
  if (result.status !== 0) {
    console.error(`\nCommand failed: ${command} ${args.join(' ')}`);
    process.exit(result.status ?? 1);
  }
}

const port = Number(readOption('--port', process.env.QUICKRISK_PORT ?? '8000'));
const host = readOption('--host', '127.0.0.1');

if (!Number.isInteger(port) || port < 1 || port > 65535) {
  console.error(`Invalid port: ${String(port)}`);
  process.exit(1);
}

const php = resolvePhp();
if (php === null) {
  console.error(
    [
      'No PHP CLI was found.',
      '',
      'Options:',
      '  1. Install PHP 8.2+ and add it to PATH, then run this command again.',
      '  2. Download the portable PHP CLI used by this repository into .tmp/php/php.exe.',
      '  3. Point at an existing binary:  set QUICKRISK_PHP=C:\\path\\to\\php.exe',
    ].join('\n'),
  );
  process.exit(1);
}

const phpVersion = spawnSync(php, ['-r', 'echo PHP_VERSION;'], { encoding: 'utf8' }).stdout ?? '';
console.log(`PHP ${phpVersion.trim()} -> ${php}`);

if (!readFlag('--no-validate')) {
  console.log('\nChecking the model (tools/validate-model.php)…');
  const check = spawnSync(php, [join('tools', 'validate-model.php')], {
    cwd: repoRoot,
    encoding: 'utf8',
    env: { ...process.env, QUICKRISK_MODEL_PATH: modelPath },
  });
  if (check.status !== 0) {
    console.error(check.stdout ?? '');
    console.error(check.stderr ?? '');
    console.error('The model did not pass validation, so nothing was served.');
    process.exit(check.status ?? 1);
  }
  console.log('Model validation passed.');
}

if (readFlag('--build') || !existsSync(distIndex)) {
  const reason = readFlag('--build') ? 'requested' : 'no build found';
  console.log(`\nBuilding the frontend (${reason})…`);
  run('npm', ['run', 'build'], { cwd: join(repoRoot, 'frontend'), shell: process.platform === 'win32' });
}

mkdirSync(tmpDir, { recursive: true });
writeFileSync(
  localConfig,
  `<?php

declare(strict_types=1);

/**
 * Generated by tools/serve-local.mjs. LOCAL DEVELOPMENT ONLY — never deploy this file.
 *
 * It allows plain HTTP and this machine's origin, and keeps rate limiting in memory so
 * that nothing is written to disk during a local run. Everything else keeps the
 * production defaults, including the zero-retention behaviour.
 */
return [
    'environment' => 'local',
    'application' => [
        'allowedOrigins' => [
            'http://127.0.0.1:${port}',
            'http://localhost:${port}',
            'http://[::1]:${port}',
        ],
        'requireHttps' => false,
    ],
    'rateLimit' => [
        'enabled' => true,
        'backend' => 'memory',
    ],
    'logging' => [
        'enabled' => true,
        'logAssessmentPayloads' => false,
        'logCalculatedResults' => false,
    ],
];
`,
  'utf8',
);

const url = `http://${host}:${port}/`;

console.log(
  [
    '',
    '='.repeat(78),
    ' FAIR QuickRisk is starting',
    '='.repeat(78),
    `  Application   ${url}`,
    `  Methodology   ${url}methodology.html`,
    `  Endpoint      ${url}api/calculate.php  (POST only)`,
    '',
    '  The model is read from  fairquickmodel/  in this repository.',
    '  Plain HTTP and localhost origins are allowed by the generated local override.',
    '  Nothing is stored: the assessment is processed in memory for one request.',
    '',
    '  Press Ctrl+C to stop.',
    '='.repeat(78),
    '',
  ].join('\n'),
);

const server = spawn(
  php,
  [
    '-d',
    'display_errors=1',
    '-d',
    'error_reporting=E_ALL',
    '-S',
    `${host}:${port}`,
    '-t',
    join(repoRoot, 'frontend', 'dist'),
    join(repoRoot, 'tools', 'local-router.php'),
  ],
  {
    cwd: repoRoot,
    stdio: 'inherit',
    env: {
      ...process.env,
      QUICKRISK_MODEL_PATH: modelPath,
      QUICKRISK_CONFIG: localConfig,
      QUICKRISK_APP_ENV: 'local',
    },
  },
);

const shutdown = () => {
  server.kill();
  process.exit(0);
};

process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
server.on('exit', (code) => process.exit(code ?? 0));

